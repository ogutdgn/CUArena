#!/usr/bin/env python3
"""Parity task generator — emit a clone probe + a Word-COM ground-truth + a tasks.json entry from a
compact descriptor, so the deep enumeration (variations + dialog fields) doesn't hand-write dozens of
near-identical probe/COM pairs. IDENTIFY-ONLY: this just creates measurement tasks; it never fixes the clone.

A descriptor is a dict:
  { id, feature, clone_call, com_action, note }
- clone_call : the ONE (or compound ;-separated) JS statement run on the selected "Revenue"
               (e.g. "PM.setFontSizePt(10.5)" or "PM.cmd('setStrike')").
- com_action : the PowerShell line(s) acting on $r = the "Revenue" range (or $doc/$w) in real Word
               (e.g. "$r.Font.Size = 10.5").

Batches (each = one usage_tier so `run.py --tier <T> --capture` captures just that batch, Word closed):
  TV = T0/T1 parameter VARIATIONS (underline styles, font sizes, line spacing).
  FD = Font dialog fields.            PD = Paragraph dialog fields.       CD = Color (More Colors) fields.
  RD = Find/Replace (doc-delta only). ID = Insert/Layout dialog fields.

The non-OOXML-measurable dialog fields (true clone gaps with NO effect path, numbering.xml-only
COM-artifacts, flow-only search modifiers) are NOT captured — they are recorded in IDENTIFIED_GAPS
below and written to tasks.json `_dialog_identified_gaps` for honest logging + the deep report.

Usage: python parity/tools/gen_tasks.py   (regenerates ALL batch descriptors + merges into tasks.json)
"""
