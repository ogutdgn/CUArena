def write_pair(d):
    with open(os.path.join(PROBES, f"{d['id']}-pilot-probe.js"), "w", encoding="utf-8") as f:
        f.write(PROBE_TMPL.format(feature=d["feature"], fix=FIX, id=d["id"], clone_call=d["clone_call"]))
    with open(os.path.join(GT, f"realword_{d['id']}.ps1"), "w", encoding="utf-8") as f:
        f.write(COM_TMPL.format(feature=d["feature"], com_action=d["com_action"]))


def main():
    os.makedirs(PROBES, exist_ok=True)
    os.makedirs(GT, exist_ok=True)
    total = 0
    new_tasks = []
    data = json.load(open(TASKS, encoding="utf-8"))
    existing = {t["id"] for t in data["tasks"]}
    for tier, control_id, tab, batch in BATCHES:
        for d in batch:
            write_pair(d)
            total += 1
            if d["id"] not in existing:
                new_tasks.append(dict(id=d["id"], control_id=control_id, feature=d["feature"], tab=tab,
                                      usage_tier=tier, action=d["feature"], realword_method="com", note=d["note"]))
    # insert all new tasks before the first pagenum/table pilot, preserving order
    idx = next((i for i, t in enumerate(data["tasks"]) if t["id"] in ("pagenum", "table")), len(data["tasks"]))
    data["tasks"][idx:idx] = new_tasks
    data["_deferred_variations"] = [
        "numbering formats (1./a)/i./A.) -> folded into the Bullets/Numbering batch as numbering.xml-only ARTIFACTS (see _dialog_identified_gaps).",
        "line spacing exactly/at-least/multiple -> ENUMERATED in the Paragraph batch (fd-ls-atleast/exactly/multiple).",
        "indentation left/right/first-line/hanging -> ENUMERATED in the Paragraph batch (fd-indent-*).",
    ]
    data["_dialog_identified_gaps"] = [
        dict(id=g[0], dialog=g[1], field=g[2], kind=g[3], detail=g[4]) for g in IDENTIFIED_GAPS
    ]
    # Adversarial-review verdicts (7 skeptic agents) — the VERIFIED classification of every finding.
